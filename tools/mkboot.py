#!/usr/bin/env python3
"""Assemble the LeactedOS boot loader (boot/stage1.asm, boot/stage2.asm) and write boot_bin.h for kernel.c.
Needs nasm. The generated header is checked in, so normal builds do not need nasm."""
import subprocess, sys, os
here = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
os.chdir(here)
for n in ("stage1", "stage2"):
    subprocess.check_call(["nasm", "-f", "bin", "boot/%s.asm" % n, "-o", "boot/%s.bin" % n])
s1 = open("boot/stage1.bin", "rb").read(); s2 = open("boot/stage2.bin", "rb").read()
assert len(s1) == 446 and len(s2) == 4096 and s2[4:8] == b"LST2"
def arr(name, b):
    lines = ["static const unsigned char %s[%d] = {" % (name, len(b))]
    for i in range(0, len(b), 16): lines.append("    " + ",".join("0x%02x" % x for x in b[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)
open("boot_bin.h", "w").write("/* generated by tools/mkboot.py from the boot/ sources - do not edit */\n" + arr("boot_stage1", s1) + "\n" + arr("boot_stage2", s2) + "\n")
print("boot_bin.h written (stage1 %d bytes, stage2 %d bytes)" % (len(s1), len(s2)))
